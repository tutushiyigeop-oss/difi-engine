#!/usr/bin/env python3
"""Stage D v0.3 UDP proof: PC <-> PS <-> real PL TX/RX, one bitstream.

This tool does NOT create golden waveforms; it saves DIFI words generated by
PL TX, echoes those exact bytes back to PL RX, and saves *actual* S2MM IQ.
"""
from __future__ import annotations

import argparse
import csv
import json
import socket
import struct
import time
from pathlib import Path

DATA_BYTES = 1052
VERSION_BYTES = 44
CONTEXT_BYTES = 108
IQ_WORDS = 256
IQ_REPLY_MAGIC = b"IQD3"


def decode_difi(data: bytes) -> dict:
    if len(data) not in (VERSION_BYTES, CONTEXT_BYTES, DATA_BYTES):
        raise ValueError(f"Unexpected DIFI UDP size={len(data)}")
    if len(data) % 4:
        raise ValueError("DIFI word alignment")
    word0, sid, oui = struct.unpack_from("!III", data)
    typ = (word0 >> 28) & 0xF
    seq = (word0 >> 16) & 0xF
    size = word0 & 0xFFFF
    expected_bytes = {5: VERSION_BYTES, 4: CONTEXT_BYTES, 1: DATA_BYTES}.get(typ)
    if expected_bytes != len(data) or size != len(data)//4:
        raise ValueError(f"DIFI type/size mismatch type={typ} word0=0x{word0:08X}")
    if oui != 0x006A621E:
        raise ValueError(f"OUI mismatch: {oui:08X}")
    if sid != (2 if typ == 5 else 1):
        raise ValueError(f"Stream ID mismatch: {sid}")
    return {"type": typ, "seq": seq, "stream_id": sid, "size_bytes": len(data), "word0": f"0x{word0:08X}"}


def signed16(word: int) -> int:
    return word - 65536 if word >= 32768 else word


def save_iq_csv(path: Path, raw: bytes) -> None:
    vals = struct.unpack(f"!{IQ_WORDS}I", raw)
    with path.open("w", newline="", encoding="utf-8") as f:
        wr = csv.writer(f)
        wr.writerow(("index", "I_signed16", "Q_signed16", "IQ_u32_hex", "source"))
        for i, w in enumerate(vals):
            wr.writerow((i, signed16(w >> 16), signed16(w & 0xffff), f"0x{w:08X}", "FPGA_RX_S2MM"))


class Board:
    def __init__(self, board: str, port: int, local: str, local_port: int, timeout: float):
        self.dst = (board, port)
        self.sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        self.sock.bind((local, local_port))
        self.sock.settimeout(timeout)
        self.timeout = timeout
        print(f"[PC] Local {self.sock.getsockname()} -> board {self.dst}")

    def close(self):
        self.sock.close()

    def send(self, message: bytes | str):
        raw = message.encode("ascii") if isinstance(message, str) else message
        sent = self.sock.sendto(raw, self.dst)
        if sent != len(raw):
            raise RuntimeError("Partial UDP send")

    def recv(self) -> bytes:
        raw, src = self.sock.recvfrom(4096)
        if src[0] != self.dst[0] or src[1] != self.dst[1]:
            raise RuntimeError(f"Unexpected sender {src}")
        return raw

    def expect(self, prefix: bytes) -> bytes:
        raw = self.recv()
        if not raw.startswith(prefix):
            raise RuntimeError(f"Expected {prefix!r}; received {raw[:200]!r}")
        print("[BOARD]", raw.decode("ascii", "replace"))
        return raw


def main() -> None:
    pa = argparse.ArgumentParser(description=__doc__)
    pa.add_argument("--board", default="192.168.1.10")
    pa.add_argument("--local-ip", default="192.168.1.20")
    pa.add_argument("--port", type=int, default=4991)
    pa.add_argument("--local-port", type=int, default=0, help="Use fixed UDP source port to resume the same board session")
    pa.add_argument("--timeout", type=float, default=10.0)
    pa.add_argument("--rounds", type=int, default=2, help="1..16; recommended 2")
    pa.add_argument("--output", type=Path, default=Path("stage_d_udp_capture"))
    pa.add_argument("--skip-utc", action="store_true", help="Only if firmware already configured in same ELF session")
    args = pa.parse_args()
    if not 1 <= args.rounds <= 16:
        pa.error("--rounds must be 1..16")
    args.output.mkdir(parents=True, exist_ok=True)
    board = Board(args.board, args.port, args.local_ip, args.local_port, args.timeout)
    try:
        board.send("STATUS")
        board.expect(b"STATUS ")
        if not args.skip_utc:
            ts = time.time_ns()
            board.send(f"UTC {ts // 1_000_000_000} {ts % 1_000_000_000}")
            board.expect(b"OK UTC ENGINE_READY")
        summary = []
        for k in range(args.rounds):
            print(f"\n=== UDP TX -> RX cycle {k} ===")
            board.send("TX")
            raw_packets = {}
            expected_types = [5, 4, 1] if k == 0 else [1]
            for expected_type in expected_types:
                packet = board.recv()
                metadata = decode_difi(packet)
                if metadata["type"] != expected_type or metadata["seq"] != (k % 16 if expected_type == 1 else 0):
                    raise RuntimeError(f"TX packet order/sequence unexpected: {metadata}")
                raw_packets[expected_type] = packet
                name = {5: "version", 4: "context", 1: "data"}[expected_type]
                (args.output / f"round{k:02d}_fpga_tx_{name}.difi").write_bytes(packet)
                print(f"[FPGA TX] {name}: {metadata}")
            board.expect(b"TXDONE ")
            board.send("RX")
            board.expect(b"READY RX ")
            for typ in expected_types:
                board.send(raw_packets[typ])
                if typ in (5, 4):
                    prefix = b"ACK PASS TYPE=VERSION" if typ == 5 else b"ACK PASS TYPE=CONTEXT"
                    board.expect(prefix)
                else:
                    raw_iq = board.recv()
                    if not raw_iq.startswith(IQ_REPLY_MAGIC) or len(raw_iq) != 4 + IQ_WORDS * 4:
                        raise RuntimeError(f"Not a real PL S2MM IQ payload (size={len(raw_iq)})")
                    actual = raw_iq[4:]
                    expected = raw_packets[1][28:]
                    if actual != expected:
                        mismatch = next((i for i in range(IQ_WORDS) if actual[i*4:i*4+4] != expected[i*4:i*4+4]), None)
                        raise RuntimeError(f"FPGA RX S2MM != FPGA TX packet IQ at sample {mismatch}")
                    (args.output / f"round{k:02d}_fpga_rx_iq.bin").write_bytes(actual)
                    save_iq_csv(args.output / f"round{k:02d}_fpga_rx_iq.csv", actual)
                    board.expect(b"ACK PASS TYPE=DATA")
                    print(f"[PASS] Round {k}: 256 exact real FPGA RX IQ samples")
                    summary.append({"round": k, "tx_sequence": k % 16, "iq_count": IQ_WORDS,
                                    "exact_iq_match": True,
                                    "tx_packets": len(expected_types)})
            board.send("STATUS")
            board.expect(b"STATUS ")
        (args.output / "summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
        print(f"\n[PASS] Stage D UDP TX/RX alternating cycles={len(summary)} actual FPGA S2MM IQ matched.")
        print(f"Evidence saved to {args.output.resolve()}")
    finally:
        board.close()


if __name__ == "__main__":
    main()
