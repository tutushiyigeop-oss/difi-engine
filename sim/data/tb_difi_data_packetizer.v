`include "difi_data_packetizer.v"
`timescale 1ns / 1ps


module tb_difi_data_packetizer;

    localparam integer MAX_SAMPLES = 256;
    localparam integer MAX_WORDS   = 7 + MAX_SAMPLES;

    // ------------------------------------------------------------------
    // 1. DUT signals
    // ------------------------------------------------------------------
    reg         aclk;
    reg         aresetn;
    reg         pkt_start;
    wire        pkt_busy;
    wire        pkt_done;

    reg  [31:0] s_axis_iq_tdata;
    reg         s_axis_iq_tvalid;
    wire        s_axis_iq_tready;

    reg  [31:0] cfg_data_stream_id;
    reg  [15:0] cfg_samples_per_packet;
    reg  [31:0] time_sec;
    reg  [63:0] time_ps;
    reg         time_valid;

    wire [31:0] m_axis_pkt_tdata;
    wire        m_axis_pkt_tvalid;
    reg         m_axis_pkt_tready;
    wire [3:0]  m_axis_pkt_tkeep;
    wire        m_axis_pkt_tlast;

    wire iq_fire  = s_axis_iq_tvalid && s_axis_iq_tready;
    wire pkt_fire = m_axis_pkt_tvalid && m_axis_pkt_tready;

    difi_data_packetizer dut (
        .aclk                   (aclk),
        .aresetn                (aresetn),
        .pkt_start              (pkt_start),
        .pkt_busy               (pkt_busy),
        .pkt_done               (pkt_done),
        .s_axis_iq_tdata        (s_axis_iq_tdata),
        .s_axis_iq_tvalid       (s_axis_iq_tvalid),
        .s_axis_iq_tready       (s_axis_iq_tready),
        .cfg_data_stream_id     (cfg_data_stream_id),
        .cfg_samples_per_packet (cfg_samples_per_packet),
        .time_sec               (time_sec),
        .time_ps                (time_ps),
        .time_valid             (time_valid),
        .m_axis_pkt_tdata       (m_axis_pkt_tdata),
        .m_axis_pkt_tvalid      (m_axis_pkt_tvalid),
        .m_axis_pkt_tready      (m_axis_pkt_tready),
        .m_axis_pkt_tkeep       (m_axis_pkt_tkeep),
        .m_axis_pkt_tlast       (m_axis_pkt_tlast)
    );

    // ------------------------------------------------------------------
    // 2. Clock / reset and test bookkeeping
    // ------------------------------------------------------------------
    initial aclk = 1'b0;
    always #5 aclk = ~aclk;  // 100 MHz

    reg [31:0] expected [0:MAX_WORDS-1];
    integer expected_len;
    integer word_index;
    integer expected_seq;
    integer wrap_count;
    integer pass_count;
    integer current_tc;
    integer packet_tag;
    integer use_reference_vector;
    reg     watch_active;

    // Backpressure is generated by ONE process only.
    reg     stall_enable;
    integer stall_hits [0:MAX_WORDS-1];
    integer stall_at_word;

    // Save a stalled beat and compare it at the next rising edge.
    reg        held_valid;
    reg [31:0] held_data;
    reg [3:0]  held_keep;
    reg        held_last;
    reg        previous_done;

    task fail;
        input [8*160-1:0] reason;
        begin
            $display("[FAIL] TC%0d time=%0t : %0s", current_tc, $time, reason);
            $finish;
        end
    endtask

    function [31:0] sample_value;
        input integer idx;
        input integer tag;
        input integer ref_vector;
        begin
            if (ref_vector != 0) begin
                case (idx)
                    0: sample_value = 32'h0001_FFFF;
                    1: sample_value = 32'h7FFF_8000;
                    2: sample_value = 32'hFFFE_0003;
                    3: sample_value = 32'h0000_0000;
                    default: sample_value = 32'hXXXX_XXXX;
                endcase
            end else begin
                // Deterministic, repeatable IQ stimulus (not random).
                sample_value = 32'h1357_9BDF ^ (tag * 32'h0001_0001)
                                             ^ (idx * 32'h0001_0103);
            end
        end
    endfunction

    // ------------------------------------------------------------------
    // 3. Output monitor + scoreboard: sample ONLY at rising-edge handshake
    // ------------------------------------------------------------------
    always @(posedge aclk) begin
        if (!aresetn) begin
            word_index    = 0;
            held_valid    = 1'b0;
            previous_done = 1'b0;
        end else begin
            if (pkt_done === 1'b1 && previous_done === 1'b1)
                fail("pkt_done stayed high for more than one clock");
            previous_done = pkt_done;

            if (held_valid) begin
                if (m_axis_pkt_tvalid !== 1'b1 ||
                    m_axis_pkt_tdata  !== held_data ||
                    m_axis_pkt_tkeep  !== held_keep ||
                    m_axis_pkt_tlast  !== held_last)
                    fail("AXIS output changed while stalled");
            end

            held_valid = (m_axis_pkt_tvalid === 1'b1 &&
                          m_axis_pkt_tready === 1'b0);
            if (held_valid) begin
                held_data = m_axis_pkt_tdata;
                held_keep = m_axis_pkt_tkeep;
                held_last = m_axis_pkt_tlast;
                // Count REAL stalled transfers, not idle cycles with TVALID=0.
                if (watch_active && stall_enable && word_index < expected_len)
                    stall_hits[word_index] = stall_hits[word_index] + 1;
            end

            if (pkt_fire) begin
                if (!watch_active)
                    fail("Unexpected output word outside an armed packet");
                if (word_index >= expected_len)
                    fail("More output words than Packet Size specifies");

                if (m_axis_pkt_tdata !== expected[word_index]) begin
                    $display("  Word[%0d]: expected=%08h actual=%08h",
                             word_index, expected[word_index], m_axis_pkt_tdata);
                    fail("Output word mismatch");
                end
                if (m_axis_pkt_tkeep !== 4'b1111)
                    fail("TKEEP must be 4'b1111");
                if (m_axis_pkt_tlast !== (word_index == expected_len-1))
                    fail("TLAST position mismatch");

                // Uncomment for an every-word trace:
                // $display("  word[%0d]=%08h last=%b", word_index,
                //          m_axis_pkt_tdata, m_axis_pkt_tlast);
                word_index = word_index + 1;
            end
        end
    end

    // ------------------------------------------------------------------
    // 4. TREADY driver: hold selected words for three full clock samples
    // ------------------------------------------------------------------
    always @(negedge aclk) begin
        if (!aresetn) begin
            m_axis_pkt_tready = 1'b1;
        end else begin
            stall_at_word = (word_index == 0  || word_index == 3 ||
                             word_index == 6  || word_index == 7 ||
                             word_index == 8  || word_index == expected_len-1);
            if (watch_active && stall_enable &&
                word_index < expected_len && stall_at_word != 0 &&
                stall_hits[word_index] < 3) begin
                m_axis_pkt_tready = 1'b0;
            end else begin
                m_axis_pkt_tready = 1'b1;
            end
        end
    end

    // ------------------------------------------------------------------
    // 5. Stimulus tasks. Drive inputs on falling edges only.
    // ------------------------------------------------------------------
    task prepare_packet;
        input integer n;
        input [31:0] sid;
        input [31:0] sec;
        input [63:0] ps;
        input integer tag;
        input integer ref_vector;
        input integer enable_stall;
        input integer gate_time;
        integer k;
        begin
            if (n < 1 || n > MAX_SAMPLES)
                fail("Invalid test configuration: sample count");
            @(negedge aclk);
            if (pkt_busy !== 1'b0 || pkt_done !== 1'b0)
                fail("DUT is not idle before a new packet");

            cfg_data_stream_id     = sid;
            cfg_samples_per_packet = n;
            time_sec               = gate_time ? 32'd0 : sec;
            time_ps                = gate_time ? 64'd0 : ps;
            time_valid             = gate_time ? 1'b0  : 1'b1;
            s_axis_iq_tdata        = 32'd0;
            s_axis_iq_tvalid       = 1'b0;

            expected_len        = 7 + n;
            word_index          = 0;
            packet_tag          = tag;
            use_reference_vector = ref_vector;
            stall_enable        = enable_stall;
            for (k = 0; k < MAX_WORDS; k = k + 1)
                stall_hits[k] = 0;

            // Golden words are constructed independently of DUT macros.
            expected[0] = 32'h1860_0000 |
                          ((expected_seq & 15) << 16) | (7 + n);
            expected[1] = sid;
            expected[2] = 32'h006A_621E;
            expected[3] = 32'h0000_0000;
            expected[4] = sec;
            expected[5] = ps[63:32];
            expected[6] = ps[31:0];
            for (k = 0; k < n; k = k + 1)
                expected[7+k] = sample_value(k, tag, ref_vector);

            watch_active = 1'b1;
        end
    endtask

    task start_packet;
        begin
            @(negedge aclk);
            if (pkt_busy !== 1'b0)
                fail("pkt_busy must be zero before pkt_start");
            pkt_start = 1'b1;
            @(negedge aclk);
            pkt_start = 1'b0;
            if (pkt_busy !== 1'b1)
                fail("pkt_busy did not assert after pkt_start");
        end
    endtask

    task send_sample;
        input [31:0] data;
        begin
            @(negedge aclk);
            s_axis_iq_tdata  = data;
            s_axis_iq_tvalid = 1'b1;
            @(posedge aclk);
            while (s_axis_iq_tready !== 1'b1)
                @(posedge aclk);
            // The rising edge above was the actual IQ handshake.
            @(negedge aclk);
            s_axis_iq_tvalid = 1'b0;
        end
    endtask

    task finish_packet;
        integer timeout_cycles;
        begin
            timeout_cycles = 0;
            // Check NOW first: pkt_done may already be high after last send_sample.
            while (pkt_done !== 1'b1 && timeout_cycles < 3000) begin
                @(negedge aclk);
                timeout_cycles = timeout_cycles + 1;
            end
            if (pkt_done !== 1'b1)
                fail("Timed out waiting for pkt_done");
            if (word_index != expected_len) begin
                $display("  Expected %0d words, observed %0d", expected_len, word_index);
                fail("Wrong number of transferred words");
            end
            if (pkt_busy !== 1'b0)
                fail("pkt_busy not cleared on completed packet");

            $display("[PASS] TC%0d packet tag=%0d N=%0d seq=%0d words=%0d",
                     current_tc, packet_tag, expected_len-7, expected_seq, word_index);
            pass_count = pass_count + 1;
            if (expected_seq == 15)
                wrap_count = wrap_count + 1;
            expected_seq = (expected_seq + 1) & 15;
            watch_active = 1'b0;

            // Ensure the completion pulse returns low before next packet.
            @(negedge aclk);
            if (pkt_done !== 1'b0)
                fail("pkt_done did not deassert after one cycle");
        end
    endtask

    task run_packet;
        input integer n;
        input [31:0] sid;
        input [31:0] sec;
        input [63:0] ps;
        input integer tag;
        input integer ref_vector;
        input integer enable_stall;
        integer k;
        begin
            prepare_packet(n, sid, sec, ps, tag, ref_vector, enable_stall, 0);
            start_packet;
            for (k = 0; k < n; k = k + 1)
                send_sample(sample_value(k, tag, ref_vector));
            finish_packet;
        end
    endtask

    // ------------------------------------------------------------------
    // 6. Main test sequence: TC01 through TC06
    // ------------------------------------------------------------------
    integer p;
    integer k;
    integer wraps_before;
    initial begin
        aresetn               = 1'b0;
        pkt_start             = 1'b0;
        s_axis_iq_tdata       = 32'd0;
        s_axis_iq_tvalid      = 1'b0;
        cfg_data_stream_id    = 32'd1;
        cfg_samples_per_packet = 16'd4;
        time_sec              = 32'd100;
        time_ps               = 64'd0;
        time_valid            = 1'b1;
        m_axis_pkt_tready     = 1'b1;
        expected_len          = 0;
        word_index            = 0;
        expected_seq          = 0;
        wrap_count            = 0;
        pass_count            = 0;
        current_tc            = 0;
        packet_tag            = 0;
        use_reference_vector  = 0;
        watch_active          = 1'b0;
        stall_enable          = 1'b0;
        held_valid            = 1'b0;
        previous_done         = 1'b0;
        for (k = 0; k < MAX_WORDS; k = k + 1)
            stall_hits[k] = 0;

        repeat (5) @(negedge aclk);
        aresetn = 1'b1;
        repeat (2) @(negedge aclk);

        // TC01: literal four-sample vector from project specification.
        current_tc = 1;
        $display("\n=== TC01: 4-sample reference vector ===");
        run_packet(4, 32'd1, 32'd100, 64'd0, 1, 1, 0);

        // TC02: both legal sample-count endpoints.
        current_tc = 2;
        $display("\n=== TC02: N=1, then N=256 ===");
        run_packet(1,   32'd1, 32'd101, 64'd1000, 2, 0, 0);
        run_packet(256, 32'd1, 32'd102, 64'd2000, 3, 0, 0);

        // TC03: 17 more packets; sequence must wrap 15 -> 0.
        current_tc = 3;
        $display("\n=== TC03: 17 consecutive packets / sequence wrap ===");
        wraps_before = wrap_count;
        for (p = 0; p < 17; p = p + 1)
            run_packet(4, 32'd1, 32'd200+p, 64'd0, 10+p, 0, 0);
        if (wrap_count == wraps_before)
            fail("Sequence number did not wrap across 17 packets");

        // TC04: stall header, first/middle payload, and final TLAST word.
        current_tc = 4;
        $display("\n=== TC04: output backpressure / AXIS stability ===");
        run_packet(4, 32'd1, 32'd300, 64'd0, 40, 0, 1);
        if (stall_hits[0] < 3 || stall_hits[3] < 3 ||
            stall_hits[6] < 3 || stall_hits[7] < 3 ||
            stall_hits[8] < 3 || stall_hits[10] < 3)
            fail("Backpressure was not actually exercised at every target");

        // TC05: first-sample snapshot survives changes halfway through packet.
        current_tc = 5;
        $display("\n=== TC05: configuration and timestamp snapshot ===");
        prepare_packet(4, 32'h0000_0011, 32'd400, 64'd1234,
                       50, 0, 0, 0);
        start_packet;
        send_sample(sample_value(0, 50, 0));
        // send_sample returns at the negedge following first IQ handshake.
        cfg_data_stream_id     = 32'h0000_0022;
        cfg_samples_per_packet = 16'd2;
        time_sec               = 32'd401;
        time_ps                = 64'd5678;
        for (k = 1; k < 4; k = k + 1)
            send_sample(sample_value(k, 50, 0));
        finish_packet;
        // The next packet must capture the updated config and timestamp.
        run_packet(2, 32'h0000_0022, 32'd401, 64'd5678, 51, 0, 0);

        // TC06: valid sample held while time source invalid; no handshake.
        current_tc = 6;
        $display("\n=== TC06: time_valid gates first IQ handshake ===");
        prepare_packet(4, 32'd1, 32'd1234, 64'd987654321,
                       60, 0, 0, 1);
        start_packet;
        @(negedge aclk);
        s_axis_iq_tdata  = sample_value(0, 60, 0);
        s_axis_iq_tvalid = 1'b1;
        repeat (4) begin
            @(posedge aclk);
            if (s_axis_iq_tready !== 1'b0 || m_axis_pkt_tvalid !== 1'b0)
                fail("First sample consumed or packet emitted when time_valid=0");
        end
        @(negedge aclk);
        time_sec   = 32'd1234;
        time_ps    = 64'd987654321;
        time_valid = 1'b1;
        @(posedge aclk);
        if (s_axis_iq_tready !== 1'b1 || s_axis_iq_tvalid !== 1'b1)
            fail("First sample not accepted when time_valid becomes 1");
        @(negedge aclk);
        s_axis_iq_tvalid = 1'b0;
        for (k = 1; k < 4; k = k + 1)
            send_sample(sample_value(k, 60, 0));
        finish_packet;

        if (pass_count != 24)
            fail("Unexpected number of completed test packets");
        $display("\nALL TESTS PASSED: TC01-TC06, %0d packets, wraps=%0d",
                 pass_count, wrap_count);
        $finish;
    end

    // Global deadlock protection (in addition to per-packet timeout).
    initial begin
        #200000;
        fail("Global simulation timeout");
    end

endmodule